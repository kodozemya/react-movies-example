import { useEffect, useState } from "react";

/**
 * Віддає значення із затримкою: поки воно змінюється, хук мовчить,
 * і повертає його аж тоді, коли зміни припинилися на `delay` мілісекунд.
 *
 * Навіщо. У макеті пошук — це поле без кнопки: результати мають з'являтися
 * під час набору. Але запит на кожну літеру означає сім запитів на слово
 * «месники» — і швидке вичерпання ліміту TMDB.
 *
 * З цим хуком запит іде один: коли користувач зупинився.
 *
 * @param {string} value значення, що часто змінюється
 * @param {number} delay пауза в мілісекундах
 * @returns {string} значення, яке «встоялося»
 */
export function useDebounced(value, delay = 400) {
  const [settled, setSettled] = useState(value);

  useEffect(() => {
    const timer = setTimeout(() => setSettled(value), delay);

    /*
      Ось де відбувається вся магія. React викликає цю функцію перед
      наступним запуском ефекту — тобто на кожній новій літері таймер
      скасовується й заводиться заново. Спрацює лише останній.

      Без clearTimeout таймери накопичувалися б, і setSettled викликався б
      стільки разів, скільки літер набрано, — тобто дебаунсу не було б узагалі.
    */
    return () => clearTimeout(timer);
  }, [value, delay]);

  return settled;
}
