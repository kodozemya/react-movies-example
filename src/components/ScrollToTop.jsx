import { useEffect } from "react";
import { useLocation } from "react-router-dom";

/**
 * Прокручує сторінку вгору після переходу за посиланням.
 *
 * Навіщо. Звичайний перехід за <a> браузер починає з початку сторінки.
 * Але react-router сторінку не перезавантажує — він лише перемальовує
 * вміст, а прокрутка лишається там, де була. Наслідок: гортаєш каталог,
 * клацаєш десяту картку — і потрапляєш на сторінку фільму, прокручену
 * до середини, ніби половину вже прочитав.
 *
 * Компонент нічого не малює — він повертає null. Так виглядає React-компонент,
 * створений заради побічної дії, а не заради розмітки.
 */
export default function ScrollToTop() {
  const { pathname } = useLocation();

  useEffect(() => {
    /*
      Стежимо саме за pathname, а не за всім location. Інакше ефект
      спрацьовував би й на зміну ?tab=movie — тобто перемикання вкладки
      смикало б сторінку вгору без причини.
    */
    window.scrollTo(0, 0);
  }, [pathname]);

  return null;
}
